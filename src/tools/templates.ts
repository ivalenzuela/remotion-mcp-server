export function writeScaffoldProjectFiles(
  projectPath: string,
  template: TemplateType,
  projectName: string
): void {
  const srcDir = path.join(projectPath, 'src');
  const componentsDir = path.join(srcDir, 'components');
  const publicAudioDir = path.join(projectPath, 'public', 'audio');
  const publicImagesDir = path.join(projectPath, 'public', 'images');
  const publicVideosDir = path.join(projectPath, 'public', 'videos');

  fs.mkdirSync(componentsDir, { recursive: true });
  fs.mkdirSync(publicAudioDir, { recursive: true });
  fs.mkdirSync(publicImagesDir, { recursive: true });
  fs.mkdirSync(publicVideosDir, { recursive: true });

  fs.writeFileSync(path.join(projectPath, 'package.json'), generatePackageJson(projectName), 'utf-8');
  fs.writeFileSync(path.join(projectPath, 'tsconfig.json'), generateTsConfig(), 'utf-8');
  fs.writeFileSync(path.join(projectPath, 'remotion.config.ts'), generateRemotionConfig(), 'utf-8');
  fs.writeFileSync(path.join(srcDir, 'index.ts'), generateIndexTs(), 'utf-8');
  fs.writeFileSync(path.join(srcDir, 'types.ts'), generateTypesTs(template), 'utf-8');
  fs.writeFileSync(path.join(srcDir, 'Root.tsx'), generateRootTsx(template), 'utf-8');

  const compCode = generateCompositionTsx(template);
  fs.writeFileSync(path.join(srcDir, 'MainComposition.tsx'), compCode, 'utf-8');
  fs.writeFileSync(path.join(srcDir, 'Composition.tsx'), compCode, 'utf-8');

  fs.writeFileSync(path.join(componentsDir, 'KenBurnsImage.tsx'), generateKenBurnsComponent(), 'utf-8');
  fs.writeFileSync(path.join(componentsDir, 'SubtitleOverlay.tsx'), generateSubtitleOverlayComponent(), 'utf-8');
  fs.writeFileSync(path.join(componentsDir, 'AudioSpectrum.tsx'), generateAudioSpectrumComponent(), 'utf-8');
  fs.writeFileSync(path.join(componentsDir, 'LowerThird.tsx'), generateLowerThirdComponent(), 'utf-8');

  logger.info(`Generated all scaffold template files for "${projectName}" (${template})`);
}
